const nodemailer = require('nodemailer');

// Create reusable transporter object using SMTP transport
let transporter = null;

const getTransporter = () => {
  if (!transporter) {
    if (process.env.SMTP_USER && process.env.SMTP_PASS) {
      transporter = nodemailer.createTransport({
        host: process.env.SMTP_HOST || 'smtp.gmail.com',
        port: parseInt(process.env.SMTP_PORT || '587', 10),
        secure: process.env.SMTP_PORT === '465',
        auth: {
          user: process.env.SMTP_USER,
          pass: process.env.SMTP_PASS,
        },
      });
    }
  }
  return transporter;
};

/**
 * Send email notification for complaint status update
 */
const sendStatusUpdateEmail = async ({ to, studentName, complaintTitle, oldStatus, newStatus, remarks, complaintId }) => {
  const subject = `[Status Update] Complaint #${complaintId.toString().slice(-6).toUpperCase()}: ${newStatus}`;
  const html = `
    <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 20px; border: 1px solid #e2e8f0; border-radius: 8px;">
      <h2 style="color: #2563eb; margin-bottom: 8px;">Smart Grievance Redressal System</h2>
      <p>Dear <strong>${studentName || 'Student'}</strong>,</p>
      <p>The status of your registered grievance has been updated.</p>
      
      <div style="background-color: #f8fafc; padding: 16px; border-radius: 6px; margin: 16px 0; border-left: 4px solid #2563eb;">
        <p style="margin: 4px 0;"><strong>Complaint ID:</strong> ${complaintId}</p>
        <p style="margin: 4px 0;"><strong>Title:</strong> ${complaintTitle}</p>
        <p style="margin: 4px 0;"><strong>New Status:</strong> <span style="background-color: #dbeafe; color: #1e40af; padding: 2px 8px; border-radius: 4px; font-weight: bold;">${newStatus}</span></p>
        ${remarks ? `<p style="margin: 8px 0 4px 0;"><strong>Admin Remarks:</strong> ${remarks}</p>` : ''}
      </div>

      ${newStatus === 'Resolved' ? '<p style="color: #059669; font-weight: bold;">Your complaint has been marked as Resolved. Please log in to your dashboard to rate the resolution and provide feedback.</p>' : ''}

      <p style="margin-top: 24px; font-size: 12px; color: #64748b;">This is an automated notification from the Institution Grievance Redressal System.</p>
    </div>
  `;

  const transport = getTransporter();
  if (transport) {
    try {
      await transport.sendMail({
        from: process.env.EMAIL_FROM || '"Smart Grievance System" <noreply@institution.edu>',
        to,
        subject,
        html,
      });
      console.log(`[Email] Status update notification sent to ${to}`);
    } catch (err) {
      console.error(`[Email Error] Failed to send email to ${to}:`, err.message);
    }
  } else {
    console.log(`[Email Mock (No SMTP Configured)] To: ${to} | Subject: "${subject}" | New Status: ${newStatus}`);
  }
};

